-- IRA SOUL database setup. Run this in Supabase SQL Editor.
create table if not exists public.enquiries (
 id bigint generated by default as identity primary key,
 name text not null,
 email text,
 phone text,
 service text,
 message text,
 status text not null default 'new' check (status in ('new','handled')),
 created_at timestamptz not null default now()
);
create table if not exists public.clients (
 id bigint generated by default as identity primary key,
 name text not null,
 url text,
 sort_order integer not null default 0,
 created_at timestamptz not null default now()
);
alter table public.enquiries enable row level security;
alter table public.clients enable row level security;
create or replace function public.ira_is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select coalesce((auth.jwt() ->> 'email') = 'irasoul.in@gmail.com', false);
$$;
-- Only the explicitly authorised admin email can read or manage private records.
create policy "IRA admin manages enquiries" on public.enquiries for all to authenticated using (public.ira_is_admin()) with check (public.ira_is_admin());
create policy "IRA admin manages clients" on public.clients for all to authenticated using (public.ira_is_admin()) with check (public.ira_is_admin());
-- Public visitors may submit enquiries, but cannot read or alter them.
create policy "Anyone can submit an enquiry" on public.enquiries for insert to anon, authenticated with check (status = 'new');
-- Public website may display client names/links.
grant select on public.clients to anon, authenticated;
create policy "Public can view clients" on public.clients for select to anon, authenticated using (true);
